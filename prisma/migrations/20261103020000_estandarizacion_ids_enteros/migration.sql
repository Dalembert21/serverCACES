ALTER TABLE "USUARIOS_ROLES" ADD CONSTRAINT "USUARIOS_ROLES_pkey" PRIMARY KEY ("USUARIO_ID", "ROL_ID");
ALTER TABLE "USUARIOS_ROLES" ADD CONSTRAINT "USUARIOS_ROLES_ROL_ID_fkey" FOREIGN KEY ("ROL_ID") REFERENCES "ROLES"("ROL_ID") ON DELETE CASCADE;


