ALTER TABLE "ROLES" ADD COLUMN IF NOT EXISTS "NUEVO_ID" SERIAL;
UPDATE "ROLES" SET "NUEVO_ID" = 1 WHERE "NOMBRE_ROL" = 'SUPERADMIN';
UPDATE "ROLES" SET "NUEVO_ID" = 2 WHERE "NOMBRE_ROL" = 'TESORERIA';
UPDATE "ROLES" SET "NUEVO_ID" = 3 WHERE "NOMBRE_ROL" = 'ESTUDIANTE';

-- Mapear en USUARIOS_ROLES
ALTER TABLE "USUARIOS_ROLES" ADD COLUMN IF NOT EXISTS "NUEVO_ROL_ID" INTEGER;
UPDATE "USUARIOS_ROLES" ur
SET "NUEVO_ROL_ID" = r."NUEVO_ID"
FROM "ROLES" r
WHERE ur."ROL_ID"::text = r."ROL_ID"::text;

-- Reemplazar columnas en ROLES
ALTER TABLE "ROLES" DROP CONSTRAINT IF EXISTS "ROLES_pkey" CASCADE;
ALTER TABLE "ROLES" DROP COLUMN "ROL_ID";
ALTER TABLE "ROLES" RENAME COLUMN "NUEVO_ID" TO "ROL_ID";
ALTER TABLE "ROLES" ADD CONSTRAINT "ROLES_pkey" PRIMARY KEY ("ROL_ID");

-- Reemplazar columnas en USUARIOS_ROLES
ALTER TABLE "USUARIOS_ROLES" DROP COLUMN "ROL_ID";
ALTER TABLE "USUARIOS_ROLES" RENAME COLUMN "NUEVO_ROL_ID" TO "ROL_ID";
