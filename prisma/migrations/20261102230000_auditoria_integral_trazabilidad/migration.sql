-- 3. Llaves Foráneas Seguras hacia USUARIOS
DO $$
DECLARE
  fk_record RECORD;
BEGIN
  -- Macro para crear claves foráneas seguras
  FOR fk_record IN
    SELECT unnest(ARRAY[
      'PROGRAMAS_ACADEMICOS:CREADO_POR:fk_prog_creado_por',
      'PROGRAMAS_ACADEMICOS:MODIFICADO_POR:fk_prog_modificado_por',
      'SUBMODULOS_ACADEMICOS:CREADO_POR:fk_subm_creado_por',
      'SUBMODULOS_ACADEMICOS:MODIFICADO_POR:fk_subm_modificado_por',
      'VERSIONES_TEMARIOS:CREADO_POR:fk_vtem_creado_por',
      'VERSIONES_TEMARIOS:MODIFICADO_POR:fk_vtem_modificado_por',
      'AREAS_ACADEMICAS:CREADO_POR:fk_area_creado_por',
      'AREAS_ACADEMICAS:MODIFICADO_POR:fk_area_modificado_por',
      'SUBAREAS_COMPETENCIAS:CREADO_POR:fk_suba_creado_por',
      'SUBAREAS_COMPETENCIAS:MODIFICADO_POR:fk_suba_modificado_por',
      'DEPARTAMENTOS:CREADO_POR:fk_dep_creado_por',
      'DEPARTAMENTOS:MODIFICADO_POR:fk_dep_modificado_por',
      'PERFILES_TRABAJADORES:CREADO_POR:fk_perf_creado_por',
      'PERFILES_TRABAJADORES:MODIFICADO_POR:fk_perf_modificado_por',
      'BANCOS_COOPERATIVAS:CREADO_POR:fk_banc_creado_por',
      'BANCOS_COOPERATIVAS:MODIFICADO_POR:fk_banc_modificado_por',
      'PLANES_SUSCRIPCION:CREADO_POR:fk_plan_creado_por',
      'PLANES_SUSCRIPCION:MODIFICADO_POR:fk_plan_modificado_por',
      'CONFIGURACIONES_SIMULADOR:CREADO_POR:fk_csim_creado_por',
      'CONFIGURACIONES_SIMULADOR:MODIFICADO_POR:fk_csim_modificado_por',
      'CASOS_CLINICOS:MODIFICADO_POR:fk_caso_modificado_por',
      'PREGUNTAS:MODIFICADO_POR:fk_preg_modificado_por',
      'VERSIONES_PREGUNTAS:CREADO_POR:fk_vpre_creado_por',
      'VERSIONES_PREGUNTAS:MODIFICADO_POR:fk_vpre_modificado_por',
      'OPCIONES_RESPUESTA:CREADO_POR:fk_opc_creado_por',
      'OPCIONES_RESPUESTA:MODIFICADO_POR:fk_opc_modificado_por',
      'BIBLIOGRAFIA_REFERENCIAS:CREADO_POR:fk_bib_creado_por',
      'BIBLIOGRAFIA_REFERENCIAS:MODIFICADO_POR:fk_bib_modificado_por',
      'MULTIMEDIA_PREGUNTAS:CREADO_POR:fk_mult_creado_por',
      'MULTIMEDIA_PREGUNTAS:MODIFICADO_POR:fk_mult_modificado_por',
      'REPORTES_PREGUNTAS:MODIFICADO_POR:fk_rep_modificado_por',
      'USUARIOS:CREADO_POR:fk_usr_creado_por',
      'USUARIOS:MODIFICADO_POR:fk_usr_modificado_por',
      'NOTAS_ESTUDIANTE_PREGUNTAS:MODIFICADO_POR:fk_nota_modificado_por',
      'PREFERENCIAS_ACCESIBILIDAD:MODIFICADO_POR:fk_pref_modificado_por',
      'PREGUNTAS_FAVORITAS:MODIFICADO_POR:fk_fav_modificado_por',
      'SUSCRIPCIONES_USUARIOS:MODIFICADO_POR:fk_susc_modificado_por',
      'TRANSACCIONES_PAGOS:MODIFICADO_POR:fk_tran_modificado_por',
      'INTENTOS_EVALUACIONES:MODIFICADO_POR:fk_inte_modificado_por',
      'USUARIOS_ROLES:ASIGNADO_POR_ID:fk_urol_asignado_por'
    ]) AS def
  LOOP
    DECLARE
      parts text[] := string_to_array(fk_record.def, ':');
      tbl_name text := parts[1];
      col_name text := parts[2];
      c_name text := parts[3];
    BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE constraint_name = c_name AND table_name = tbl_name
      ) THEN
        EXECUTE format(
          'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES "USUARIOS"("USUARIO_ID") ON DELETE SET NULL ON UPDATE CASCADE;',
          tbl_name, c_name, col_name
        );
      END IF;
    EXCEPTION WHEN OTHERS THEN
      -- Log o continuar si los datos contienen referencias huérfanas
      RAISE NOTICE 'Constraint % no pudo ser añadida: %', c_name, SQLERRM;
    END;
  END LOOP;
END $$;

