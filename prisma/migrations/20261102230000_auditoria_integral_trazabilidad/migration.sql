-- 6. Función de Auditoría Universal PostgreSQL (Trigger Engine)
CREATE OR REPLACE FUNCTION "fn_auditoria_sistema"()
RETURNS TRIGGER AS $$
DECLARE
  v_tabla TEXT := TG_TABLE_NAME;
  v_accion TEXT := TG_OP;
  v_registro_id TEXT := '';
  v_datos_ant JSONB := NULL;
  v_datos_nuev JSONB := NULL;
  v_usuario_id TEXT := NULL;
  v_tipo_actor TEXT := 'USUARIO';
  v_ip TEXT := '127.0.0.1';
  v_user_agent TEXT := 'Sistema Backend';
  v_modulo TEXT := TG_TABLE_NAME;
BEGIN
  -- Leer variables de sesión o contexto de transacción si existen
  BEGIN
    v_usuario_id := NULLIF(current_setting('app.current_user_id', true), '');
    v_tipo_actor := COALESCE(NULLIF(current_setting('app.current_actor_type', true), ''), 'USUARIO');
    v_ip := COALESCE(NULLIF(current_setting('app.current_ip', true), ''), '127.0.0.1');
    v_user_agent := COALESCE(NULLIF(current_setting('app.current_user_agent', true), ''), 'Sistema Backend CACES');
    v_modulo := COALESCE(NULLIF(current_setting('app.current_module', true), ''), TG_TABLE_NAME);
  EXCEPTION WHEN OTHERS THEN
    -- Fallback si no están configuradas
  END;

  IF v_accion = 'INSERT' THEN
    v_datos_nuev := to_jsonb(NEW);
    -- Enmascarar secretos sensibles
    IF v_tabla = 'USUARIOS' THEN
      v_datos_nuev := v_datos_nuev - 'CONTRASENA_ENCRIPTADA' || jsonb_build_object('CONTRASENA_ENCRIPTADA', '[PROTEGIDO]');
    ELSIF v_tabla = 'SESIONES_AUTENTICACION' THEN
      v_datos_nuev := v_datos_nuev - 'HASH_TOKEN_REFRESCO' || jsonb_build_object('HASH_TOKEN_REFRESCO', '[PROTEGIDO]');
    ELSIF v_tabla = 'TOKENS_RECUPERACION_CONTRASENA' THEN
      v_datos_nuev := v_datos_nuev - 'HASH_TOKEN' || jsonb_build_object('HASH_TOKEN', '[PROTEGIDO]');
    END IF;

    -- Extraer el ID del nuevo registro
    v_registro_id := COALESCE(
      v_datos_nuev->>'PROGRAMA_ACADEMICO_ID',
      v_datos_nuev->>'SUBMODULO_ACADEMICO_ID',
      v_datos_nuev->>'USUARIO_ID',
      v_datos_nuev->>'PREGUNTA_ID',
      v_datos_nuev->>'BANCO_COOPERATIVA_ID',
      v_datos_nuev->>'DEPARTAMENTO_ID',
      v_datos_nuev->>'AREA_ACADEMICA_ID',
      v_datos_nuev->>'SUBAREA_COMPETENCIA_ID',
      v_datos_nuev->>'VERSION_TEMARIO_ID',
      v_datos_nuev->>'PERFIL_TRABAJADOR_ID',
      v_datos_nuev->>'PLAN_SUSCRIPCION_ID',
      v_datos_nuev->>'CONFIGURACION_SIMULADOR_ID',
      v_datos_nuev->>'CASO_CLINICO_ID',
      v_datos_nuev->>'VERSION_PREGUNTA_ID',
      v_datos_nuev->>'OPCION_RESPUESTA_ID',
      v_datos_nuev->>'MULTIMEDIA_PREGUNTA_ID',
      v_datos_nuev->>'BIBLIOGRAFIA_REFERENCIA_ID',
      v_datos_nuev->>'REPORTE_PREGUNTA_ID',
      v_datos_nuev->>'INTENTO_EVALUACION_ID',
      v_datos_nuev->>'RESPUESTA_INTENTO_ID',
      v_datos_nuev->>'RESULTADO_INTENTO_ID',
      v_datos_nuev->>'DOMINIO_COGNITIVO_ID',
      v_datos_nuev->>'SUSCRIPCION_USUARIO_ID',
      v_datos_nuev->>'TRANSACCION_PAGO_ID',
      v_datos_nuev->>'PREFERENCIA_ACCESIBILIDAD_ID',
      v_datos_nuev->>'PREGUNTA_FAVORITA_ID',
      v_datos_nuev->>'NOTA_ESTUDIANTE_ID',
      v_datos_nuev->>'ROL_ID',
      v_datos_nuev->>'SESION_ID',
      v_datos_nuev->>'id',
      ''
    );

    IF v_usuario_id IS NULL THEN
      v_usuario_id := COALESCE(
        v_datos_nuev->>'CREADO_POR',
        v_datos_nuev->>'AUTOR_DOCENTE_ID',
        v_datos_nuev->>'AUTOR_USUARIO_ID',
        v_datos_nuev->>'USUARIO_ID'
      );
    END IF;

  ELSIF v_accion = 'UPDATE' THEN
    v_datos_ant := to_jsonb(OLD);
    v_datos_nuev := to_jsonb(NEW);

    -- Enmascarar secretos sensibles
    IF v_tabla = 'USUARIOS' THEN
      v_datos_ant := v_datos_ant - 'CONTRASENA_ENCRIPTADA' || jsonb_build_object('CONTRASENA_ENCRIPTADA', '[PROTEGIDO]');
      v_datos_nuev := v_datos_nuev - 'CONTRASENA_ENCRIPTADA' || jsonb_build_object('CONTRASENA_ENCRIPTADA', '[PROTEGIDO]');
    ELSIF v_tabla = 'SESIONES_AUTENTICACION' THEN
      v_datos_ant := v_datos_ant - 'HASH_TOKEN_REFRESCO' || jsonb_build_object('HASH_TOKEN_REFRESCO', '[PROTEGIDO]');
      v_datos_nuev := v_datos_nuev - 'HASH_TOKEN_REFRESCO' || jsonb_build_object('HASH_TOKEN_REFRESCO', '[PROTEGIDO]');
    ELSIF v_tabla = 'TOKENS_RECUPERACION_CONTRASENA' THEN
      v_datos_ant := v_datos_ant - 'HASH_TOKEN' || jsonb_build_object('HASH_TOKEN', '[PROTEGIDO]');
      v_datos_nuev := v_datos_nuev - 'HASH_TOKEN' || jsonb_build_object('HASH_TOKEN', '[PROTEGIDO]');
    END IF;

    v_registro_id := COALESCE(
      v_datos_nuev->>'PROGRAMA_ACADEMICO_ID',
