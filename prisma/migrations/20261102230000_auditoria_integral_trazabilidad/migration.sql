-- 7. Triggers de Protección e Inmutabilidad de la Auditoría
CREATE OR REPLACE FUNCTION "fn_proteger_historial_auditoria"()
RETURNS TRIGGER AS $$
BEGIN
  RAISE EXCEPTION 'VIOLACION DE SEGURIDAD: Los registros del historial de auditoría son estrictamente inmutables y no pueden modificarse ni eliminarse.';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS "trg_proteger_auditoria_operaciones" ON "AUDITORIA_OPERACIONES_SISTEMA";
