      CASE WHEN v_datos_nuev ? 'INTENTO_EVALUACION_ID' AND v_datos_nuev ? 'VERSION_PREGUNTA_ID'
           THEN (v_datos_nuev->>'INTENTO_EVALUACION_ID') || ':' || (v_datos_nuev->>'VERSION_PREGUNTA_ID')
           ELSE NULL END,
      v_datos_nuev->>'id',
      ''
    );

