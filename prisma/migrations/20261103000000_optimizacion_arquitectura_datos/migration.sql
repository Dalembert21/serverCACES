  ELSIF v_accion = 'DELETE' THEN
    v_datos_ant := to_jsonb(OLD);

    IF v_tabla = 'USUARIOS' THEN
      v_datos_ant := v_datos_ant - 'CONTRASENA_ENCRIPTADA' || jsonb_build_object('CONTRASENA_ENCRIPTADA', '[PROTEGIDO]');
    ELSIF v_tabla = 'SESIONES_AUTENTICACION' THEN
      v_datos_ant := v_datos_ant - 'HASH_TOKEN_REFRESCO' || jsonb_build_object('HASH_TOKEN_REFRESCO', '[PROTEGIDO]');
    ELSIF v_tabla = 'TOKENS_RECUPERACION_CONTRASENA' THEN
      v_datos_ant := v_datos_ant - 'HASH_TOKEN' || jsonb_build_object('HASH_TOKEN', '[PROTEGIDO]');
    END IF;

    v_registro_id := COALESCE(
      v_datos_ant->>'PROGRAMA_ACADEMICO_ID',
      v_datos_ant->>'SUBMODULO_ACADEMICO_ID',
      v_datos_ant->>'USUARIO_ID',
      v_datos_ant->>'PREGUNTA_ID',
      v_datos_ant->>'BANCO_COOPERATIVA_ID',
      v_datos_ant->>'DEPARTAMENTO_ID',
      v_datos_ant->>'AREA_ACADEMICA_ID',
      v_datos_ant->>'SUBAREA_COMPETENCIA_ID',
      v_datos_ant->>'VERSION_TEMARIO_ID',
      v_datos_ant->>'PLAN_SUSCRIPCION_ID',
      v_datos_ant->>'CONFIGURACION_SIMULADOR_ID',
      v_datos_ant->>'CASO_CLINICO_ID',
      v_datos_ant->>'VERSION_PREGUNTA_ID',
      v_datos_ant->>'OPCION_RESPUESTA_ID',
      v_datos_ant->>'MULTIMEDIA_PREGUNTA_ID',
      v_datos_ant->>'BIBLIOGRAFIA_REFERENCIA_ID',
      v_datos_ant->>'REPORTE_PREGUNTA_ID',
      v_datos_ant->>'INTENTO_EVALUACION_ID',
      v_datos_ant->>'RESULTADO_INTENTO_ID',
      v_datos_ant->>'DOMINIO_COGNITIVO_ID',
      v_datos_ant->>'SUSCRIPCION_USUARIO_ID',
      v_datos_ant->>'TRANSACCION_PAGO_ID',
      v_datos_ant->>'NOTA_ESTUDIANTE_ID',
      v_datos_ant->>'ROL_ID',
      v_datos_ant->>'SESION_ID',
      CASE WHEN v_datos_ant ? 'PREGUNTA_ID' AND v_datos_ant ? 'USUARIO_ID'
           THEN (v_datos_ant->>'USUARIO_ID') || ':' || (v_datos_ant->>'PREGUNTA_ID')
           ELSE NULL END,
      CASE WHEN v_datos_ant ? 'INTENTO_EVALUACION_ID' AND v_datos_ant ? 'VERSION_PREGUNTA_ID'
           THEN (v_datos_ant->>'INTENTO_EVALUACION_ID') || ':' || (v_datos_ant->>'VERSION_PREGUNTA_ID')
           ELSE NULL END,
      v_datos_ant->>'id',
      ''
    );

    IF v_usuario_id IS NULL THEN
      v_usuario_id := COALESCE(
        v_datos_ant->>'MODIFICADO_POR',
        v_datos_ant->>'CREADO_POR',
        v_datos_ant->>'USUARIO_ID'
      );
    END IF;
  END IF;

  IF v_usuario_id IS NULL THEN
    v_tipo_actor := 'SISTEMA';
  END IF;

  INSERT INTO "AUDITORIA_OPERACIONES_SISTEMA" (
    "USUARIO_OPERADOR_ID",
    "TIPO_ACCION",
    "NOMBRE_TABLA_AFECTADA",
    "IDENTIFICADOR_REGISTRO_AFECTADO",
    "DATOS_ANTERIORES_JSON",
    "DATOS_NUEVOS_JSON",
    "MOTIVO_JUSTIFICACION",
    "DIRECCION_IP_CLIENTE",
    "AGENTE_DISPOSITIVO_USER_AGENT",
    "FECHA_HORA_REGISTRO",
    "TIPO_ACTOR",
    "MODULO"
  ) VALUES (
    v_usuario_id,
    v_accion,
    v_tabla,
    v_registro_id,
    v_datos_ant,
    v_datos_nuev,
    NULL,
    v_ip,
    v_user_agent,
    CURRENT_TIMESTAMP,
    v_tipo_actor,
    v_modulo
  );

  IF v_accion = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
