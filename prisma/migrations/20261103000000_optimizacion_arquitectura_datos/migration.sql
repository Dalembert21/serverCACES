-- 1. Migración y Consolidación de Roles en RBAC (USUARIOS_ROLES)
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'USUARIOS' AND column_name = 'ROL'
  ) THEN
    INSERT INTO "USUARIOS_ROLES" ("USUARIO_ID", "ROL_ID", "FECHA_ASIGNACION")
    SELECT u."USUARIO_ID", r."ROL_ID", CURRENT_TIMESTAMP
    FROM "USUARIOS" u
    JOIN "ROLES" r ON UPPER(TRIM(u."ROL")) = UPPER(TRIM(r."NOMBRE_ROL"::text))
    ON CONFLICT ("USUARIO_ID", "ROL_ID") DO NOTHING;

    ALTER TABLE "USUARIOS" DROP COLUMN "ROL";
  END IF;
END $$;

-- 2. Eliminación de redundancia PERFILES_TRABAJADORES.DEPARTAMENTO
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'PERFILES_TRABAJADORES' AND column_name = 'DEPARTAMENTO'
  ) THEN
    UPDATE "PERFILES_TRABAJADORES" pt
    SET "DEPARTAMENTO_ID" = d."DEPARTAMENTO_ID"
    FROM "DEPARTAMENTOS" d
    WHERE pt."DEPARTAMENTO_ID" IS NULL
      AND pt."DEPARTAMENTO" IS NOT NULL
      AND LOWER(TRIM(pt."DEPARTAMENTO")) = LOWER(TRIM(d."NOMBRE_DEPARTAMENTO"));

    DROP INDEX IF EXISTS "PERFILES_TRABAJADORES_DEPARTAMENTO_idx";
    ALTER TABLE "PERFILES_TRABAJADORES" DROP COLUMN "DEPARTAMENTO";
  END IF;
END $$;

