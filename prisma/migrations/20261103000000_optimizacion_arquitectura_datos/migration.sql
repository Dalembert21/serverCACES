      CASE WHEN v_datos_nuev ? 'PREGUNTA_ID' AND v_datos_nuev ? 'USUARIO_ID'
           THEN (v_datos_nuev->>'USUARIO_ID') || ':' || (v_datos_nuev->>'PREGUNTA_ID')
           ELSE NULL END,
      CASE WHEN v_datos_nuev ? 'INTENTO_EVALUACION_ID' AND v_datos_nuev ? 'VERSION_PREGUNTA_ID'
