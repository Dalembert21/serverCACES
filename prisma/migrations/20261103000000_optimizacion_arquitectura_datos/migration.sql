      v_datos_nuev->>'INTENTO_EVALUACION_ID',
      v_datos_nuev->>'RESULTADO_INTENTO_ID',
      v_datos_nuev->>'DOMINIO_COGNITIVO_ID',
      v_datos_nuev->>'SUSCRIPCION_USUARIO_ID',
      v_datos_nuev->>'TRANSACCION_PAGO_ID',
      v_datos_nuev->>'NOTA_ESTUDIANTE_ID',
      v_datos_nuev->>'ROL_ID',
      v_datos_nuev->>'SESION_ID',
