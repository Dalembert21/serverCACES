-- Eliminación de dependencias de prueba/temporales
DELETE FROM "CONFIGURACIONES_SIMULADOR"
WHERE "PROGRAMA_ACADEMICO_ID" NOT IN ('MEDICINA', 'ENFERMERIA', 'ODONTOLOGIA');

DELETE FROM "VERSIONES_TEMARIOS"
WHERE "PROGRAMA_ACADEMICO_ID" NOT IN ('MEDICINA', 'ENFERMERIA', 'ODONTOLOGIA');

DELETE FROM "SUBMODULOS_ACADEMICOS"
WHERE "PROGRAMA_ACADEMICO_ID" NOT IN ('MEDICINA', 'ENFERMERIA', 'ODONTOLOGIA');

UPDATE "USUARIOS"
SET "PROGRAMA_ACTIVO_ID" = NULL
WHERE "PROGRAMA_ACTIVO_ID" NOT IN ('MEDICINA', 'ENFERMERIA', 'ODONTOLOGIA');

-- Limpieza de programas: solo mantener Medicina, Enfermería y Odontología
DELETE FROM "PROGRAMAS_ACADEMICOS"
WHERE "PROGRAMA_ACADEMICO_ID" NOT IN ('MEDICINA', 'ENFERMERIA', 'ODONTOLOGIA');

-- Estandarización de nombres
UPDATE "PROGRAMAS_ACADEMICOS" SET "NOMBRE_PROGRAMA" = 'Medicina' WHERE "PROGRAMA_ACADEMICO_ID" = 'MEDICINA';
UPDATE "PROGRAMAS_ACADEMICOS" SET "NOMBRE_PROGRAMA" = 'Enfermería' WHERE "PROGRAMA_ACADEMICO_ID" = 'ENFERMERIA';
UPDATE "PROGRAMAS_ACADEMICOS" SET "NOMBRE_PROGRAMA" = 'Odontología' WHERE "PROGRAMA_ACADEMICO_ID" = 'ODONTOLOGIA';

-- Configuración de PK automática por defecto
ALTER TABLE "PROGRAMAS_ACADEMICOS" ALTER COLUMN "PROGRAMA_ACADEMICO_ID" SET DEFAULT gen_random_uuid()::text;

-- Eliminación de columnas redundantes
ALTER TABLE "PROGRAMAS_ACADEMICOS" DROP COLUMN IF EXISTS "CODIGO_OFICIAL_CACES";
ALTER TABLE "PROGRAMAS_ACADEMICOS" DROP COLUMN IF EXISTS "DESCRIPCION_PROGRAMA";

-- Asegurar restricción UNIQUE en NOMBRE_PROGRAMA
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'PROGRAMAS_ACADEMICOS_NOMBRE_PROGRAMA_key'
  ) THEN
    ALTER TABLE "PROGRAMAS_ACADEMICOS" ADD CONSTRAINT "PROGRAMAS_ACADEMICOS_NOMBRE_PROGRAMA_key" UNIQUE ("NOMBRE_PROGRAMA");
  END IF;
END $$;

